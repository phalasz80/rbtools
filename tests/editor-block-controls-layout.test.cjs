"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const src=fs.readFileSync(path.join(__dirname,"..","index.html"),"utf8");
const rules=selector=>[...src.matchAll(/([^{}]+)\{([^{}]*)\}/g)].filter(m=>m[1].trim()===selector).map(m=>m[2]);
const block=rules("#rbtools-app .admin-block").join(";");
const controls=rules("#rbtools-app .admin-block-controls").join(";");
assert.match(block,/display:flex/);
assert.match(block,/flex-wrap:wrap/);
assert.match(block,/align-items:flex-start/);
assert.doesNotMatch(block,/padding-right:(?:38|44)px/);
assert.match(controls,/position:static/);
assert.doesNotMatch(controls,/position:absolute|flex-direction:column/);
assert.match(controls,/flex-wrap:wrap/);
assert.match(controls,/justify-content:flex-end/);
assert.match(controls,/max-width:100%/);
assert.match(rules("#rbtools-app .admin-block>:not(.admin-block-controls)").join(";"),/flex:1 1 200px;min-width:0/);
assert.match(rules("#rbtools-app .admin-block-controls button").join(";"),/min-height:28px/);
assert.match(src,/mk\("×","Blokk törlése"/);
assert.match(src,/box\.append\(handle,mk\("↑","Feljebb"/);
assert.match(src,/shell\.appendChild\(adminBlockControls\(block\)\)/);
console.log("WYSIWYG block controls: in-flow compact row, wrapping and all actions retained: PASS");